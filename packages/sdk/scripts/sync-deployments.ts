// Mirrors contracts/deployments/<chainId>.json into src/deployments/chains/ and regenerates
// src/deployments/registry.ts, which imports them so they are bundled at build time.
// Without a contracts/deployments directory (a package checkout), the committed copies are kept.
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = resolve(here, "../../../contracts/deployments");
const chainsDir = resolve(here, "../src/deployments/chains");
const registryFile = resolve(here, "../src/deployments/registry.ts");

const isChainFile = (f: string) => /^\d+\.json$/.test(f);

mkdirSync(chainsDir, { recursive: true });
if (existsSync(sourceDir)) {
  const wanted = new Set(readdirSync(sourceDir).filter(isChainFile));
  for (const f of readdirSync(chainsDir).filter(isChainFile)) {
    if (!wanted.has(f)) rmSync(join(chainsDir, f));
  }
  for (const f of wanted) copyFileSync(join(sourceDir, f), join(chainsDir, f));
}

const chainIds = readdirSync(chainsDir)
  .filter(isChainFile)
  .map((f) => Number(f.slice(0, -".json".length)))
  .sort((a, b) => a - b);

const lines = [
  "// Generated by scripts/sync-deployments.ts from contracts/deployments. Do not edit by hand.",
  ...chainIds.map((id) => `import chain${id} from "./chains/${id}.json";`),
  "",
  "/** Raw deployment files bundled at build time, keyed by chain id. Validate with parseDeployment. */",
  `export const rawDeployments: Readonly<Record<number, unknown>> = {${chainIds
    .map((id) => ` ${id}: chain${id}`)
    .join(",")}${chainIds.length ? " " : ""}};`,
  "",
];
const next = lines.join("\n");
writeFileSync(registryFile, next);
console.log(`deployments bundled for chains: ${chainIds.length ? chainIds.join(", ") : "(none)"}`);
