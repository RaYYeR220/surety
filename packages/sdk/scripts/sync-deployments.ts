// Mirrors the deployment files into src/deployments/chains/ and regenerates src/deployments/registry.ts, which
// imports them so they are bundled at build time:
//   contracts/deployments/<chainId>.json      the current deployment (schema version 2)  -> chains/<chainId>.json
//   contracts/deployments/v<N>/<chainId>.json earlier deployments, kept with their proof  -> chains/v<N>/<chainId>.json
// Without a contracts/deployments directory (a package checkout), the committed copies are kept.
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = resolve(here, "../../../contracts/deployments");
const chainsDir = resolve(here, "../src/deployments/chains");
const registryFile = resolve(here, "../src/deployments/registry.ts");

const isChainFile = (f: string) => /^\d+\.json$/.test(f);
const isArchiveDir = (f: string) => /^v\d+$/.test(f);
const chainIdsIn = (dir: string) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter(isChainFile)
        .map((f) => Number(f.slice(0, -".json".length)))
        .sort((a, b) => a - b)
    : [];
const subdirs = (dir: string) =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
        .filter((e) => e.isDirectory() && isArchiveDir(e.name))
        .map((e) => e.name)
    : [];

/** Makes `to` hold exactly the chain files of `from`. */
function mirror(from: string, to: string): void {
  mkdirSync(to, { recursive: true });
  const wanted = new Set(readdirSync(from).filter(isChainFile));
  for (const f of readdirSync(to).filter(isChainFile)) {
    if (!wanted.has(f)) rmSync(join(to, f));
  }
  for (const f of wanted) copyFileSync(join(from, f), join(to, f));
}

mkdirSync(chainsDir, { recursive: true });
if (existsSync(sourceDir)) {
  mirror(sourceDir, chainsDir);
  const archives = new Set(subdirs(sourceDir));
  for (const dir of subdirs(chainsDir)) {
    if (!archives.has(dir)) rmSync(join(chainsDir, dir), { recursive: true });
  }
  for (const dir of archives) mirror(join(sourceDir, dir), join(chainsDir, dir));
}

const current = chainIdsIn(chainsDir);
const archives = subdirs(chainsDir)
  .map((dir) => ({ dir, version: Number(dir.slice(1)), chainIds: chainIdsIn(join(chainsDir, dir)) }))
  .sort((a, b) => a.version - b.version);

const record = (entries: string[]) => `{${entries.join(",")}${entries.length ? " " : ""}}`;
const lines = [
  "// Generated by scripts/sync-deployments.ts from contracts/deployments. Do not edit by hand.",
  ...current.map((id) => `import chain${id} from "./chains/${id}.json";`),
  ...archives.flatMap((a) => a.chainIds.map((id) => `import ${a.dir}chain${id} from "./chains/${a.dir}/${id}.json";`)),
  "",
  "/** Current deployment files bundled at build time, keyed by chain id. Validate with parseDeployment. */",
  `export const rawDeployments: Readonly<Record<number, unknown>> = ${record(current.map((id) => ` ${id}: chain${id}`))};`,
  "",
  "/** Earlier deployments (contracts/deployments/v<N>/), keyed by schema version, then chain id. */",
  `export const rawArchivedDeployments: Readonly<Record<number, Readonly<Record<number, unknown>>>> = ${record(
    archives.map((a) => ` ${a.version}: ${record(a.chainIds.map((id) => ` ${id}: ${a.dir}chain${id}`))}`),
  )};`,
  "",
];
writeFileSync(registryFile, lines.join("\n"));
const summary = [
  `current: ${current.length ? current.join(", ") : "(none)"}`,
  ...archives.map((a) => `${a.dir}: ${a.chainIds.join(", ") || "(none)"}`),
];
console.log(`deployments bundled — ${summary.join("; ")}`);
